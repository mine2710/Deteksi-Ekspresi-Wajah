import tensorflow as tf
from tensorflow.keras.preprocessing.image import ImageDataGenerator
from tensorflow.keras.applications import MobileNetV2
from tensorflow.keras.layers import Dense, GlobalAveragePooling2D, Dropout
from tensorflow.keras.models import Model
from tensorflow.keras.optimizers import Adam

# 1. Siapkan Data Generator (Ambil dari folder hasil augmentasi tadi)
TRAIN_DIR = '/content/drive/MyDrive/Dataset_Siap_Training'
IMG_SIZE = (224, 224) # Ukuran standar MobileNet
BATCH_SIZE = 16

# Define the classes explicitly (from the previous cell's 'classes' variable)
# This is crucial to match the model's output layer
TARGET_CLASSES = ['Bingung', 'Lelah', 'Mengerti']

train_datagen = ImageDataGenerator(
    rescale=1./255,       # Normalisasi piksel
    validation_split=0.2  # 20% buat ujian (validasi)
)

print("Menyiapkan data Training...")
train_generator = train_datagen.flow_from_directory(
    TRAIN_DIR,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='categorical',
    subset='training',
    classes=TARGET_CLASSES # Specify the target classes
)

print("Menyiapkan data Validasi...")
val_generator = train_datagen.flow_from_directory(
    TRAIN_DIR,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='categorical',
    subset='validation',
    classes=TARGET_CLASSES # Specify the target classes
)

# 2. Bangun Model (Transfer Learning)
# Ambil otak MobileNet tapi buang bagian kepalanya (include_top=False)
base_model = MobileNetV2(weights='imagenet', include_top=False, input_shape=(224, 224, 3))

# Bekukan base_model biar ilmunya gak hilang
base_model.trainable = False

# Tambahkan kepala baru sesuai kasus kita (3 Kelas)
x = base_model.output
x = GlobalAveragePooling2D()(x)
x = Dense(128, activation='relu')(x)
x = Dropout(0.2)(x) # Biar gak overfitting
predictions = Dense(len(TARGET_CLASSES), activation='softmax')(x) # Use len(TARGET_CLASSES) for robustness

model = Model(inputs=base_model.input, outputs=predictions)

# 3. Compile Model
model.compile(optimizer=Adam(learning_rate=0.0001),
              loss='categorical_crossentropy',
              metrics=['accuracy'])

# 4. Mulai Training
print("\nMulai Training CNN... (Sabar ya)")
history = model.fit(
    train_generator,
    epochs=20,  # Coba 20 putaran dulu
    validation_data=val_generator
)

# 5. Simpan Model
model.save('model_cnn_tubes.h5')
print("\nSelesai! Model disimpan sebagai 'model_cnn_tubes.h5'")

