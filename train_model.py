    file_names = os.listdir(source_dir)

    print(f"Sedang memproses kelas: {kelas} ({len(file_names)} gambar asli)...")

    # Mulai Augmentasi
    count = 0
    for file_name in file_names:
        img_path = os.path.join(source_dir, file_name)

        # Cek apakah file gambar valid
        if not file_name.lower().endswith(('.png', '.jpg', '.jpeg')):
            continue

        # Load gambar
        img = load_img(img_path)
        x = img_to_array(img)
        x = x.reshape((1,) + x.shape)

        # Generate variasi baru
        i = 0
        for batch in datagen.flow(x, batch_size=1, save_to_dir=save_dir, save_prefix='aug', save_format='jpg'):
            i += 1
            count += 1
            if i >= 5: # Dari 1 foto bikin 5 variasi
                break

    print(f"Selesai! Total gambar '{kelas}' sekarang ada di folder output.")

